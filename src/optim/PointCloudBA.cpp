// ---- small autograd helpers (kept local; libtorch C++ API) ----

inline TensorOptions opts() {
    return TensorOptions().dtype(torch::kFloat32).device(torch::kCUDA);
}

// 1D Gaussian window of size `win`, normalized to sum 1. Used for SSIM.
Tensor gaussianWindow1d(int win, float sigma) {
    auto t = torch::arange(win, TensorOptions().dtype(torch::kFloat32))
                 - float(win - 1) / 2.f;
    auto g = torch::exp(-(t * t) / (2.f * sigma * sigma));
    return g / g.sum();
}

// SSIM(x, y) over a single channel using a win x win Gaussian window.
Tensor ssimSingleChannel(const Tensor& x0, const Tensor& y0, int win, float sigma) {
    auto x = x0.unsqueeze(0).unsqueeze(0);  // [1,1,H,W]
    auto y = y0.unsqueeze(0).unsqueeze(0);

    auto g1 = gaussianWindow1d(win, sigma);
    auto window = (g1.unsqueeze(0) * g1.unsqueeze(1))
                      .unsqueeze(0).unsqueeze(0).to(x);  // [1,1,win,win]

    constexpr float C1 = 0.01f * 0.01f;
    constexpr float C2 = 0.03f * 0.03f;

    int pad = win / 2;
    auto muX  = torch::conv2d(x,      window, /*bias=*/{}, /*stride=*/{}, pad);
    auto muY  = torch::conv2d(y,      window, {}, {}, pad);
    auto muX2 = muX * muX;
    auto muY2 = muY * muY;
    auto muXY = muX * muY;

    auto sigmaX2 = torch::conv2d(x * x, window, {}, {}, pad) - muX2;
    auto sigmaY2 = torch::conv2d(y * y, window, {}, {}, pad) - muY2;
    auto sigmaXY = torch::conv2d(x * y, window, {}, {}, pad) - muXY;

    auto ssimMap =
        ((2.f * muXY + C1) * (2.f * sigmaXY + C2)) /
        ((muX2 + muY2 + C1) * (sigmaX2 + sigmaY2 + C2));
    return ssimMap.mean();
}

// ---------------------------------------------------------------------------
// Differentiable EWA Gaussian-splatting forward pass (fully vectorized).
//
// Each Gaussian i contributes to pixels within a fixed screen-space radius R
// a weight  w = alpha_i * exp(-0.5 * d2 / sigma_i^2)  where d2 is the squared
// pixel distance to the projected centre and alpha_i = sigmoid(opacity_i).
// The rendered colour is the normalized weighted sum
//     C(p) = sum_i w_i c_i / (sum_i w_i + eps).
//
// Implementation: for every splat, a (2R+1)x(2R+1) patch of pixel offsets is
// generated by broadcasting, the per-pair weights and colour contributions are
// computed as GPU tensors, then scattered into per-pixel accumulators via
// `scatter_add_`. No per-splat CPU loop or `.item()` sync — the entire pass
// is a sequence of vectorized tensor ops so autograd records the full graph.
//
// What is differentiable: weight w (→ position via projection, scale via
// sigma, opacity via alpha) and the colour contribution w*c (→ color). The
// integer pixel index (which pixels a splat touches) is treated as a constant
// — the standard approximation used in tile-based differentiable splatting.
// ---------------------------------------------------------------------------
Tensor renderGaussians(
    const Tensor& position,   // [N,3]
    const Tensor& color,      // [N,3]
    const Tensor& scale,      // [N,1] log-space isotropic
    const Tensor& opacity,    // [N,1] logit
    const Tensor& view,       // [4,4]
    float fx, float fy, float cx, float cy,
    int W, int H,
    int pixelRadius)          // fixed screen radius R (pixels)
{
    auto o = opts();
    int64_t N = position.size(0);
    int K = 2 * pixelRadius + 1;

    // --- Project centres to the image plane ---
    auto ones = torch::ones({N, 1}, o);
    auto pHom = torch::cat({position, ones}, /*dim=*/1);   // [N,4]
    auto pCam = pHom.mm(view.t());                          // [N,4]
    auto z = pCam.slice(1, 2, 3).clamp_min(1e-4f);          // [N,1]
    auto xy = pCam.slice(1, 0, 2) / z;                      // [N,2]
    auto sx = xy.slice(1, 0, 1) * fx + cx;                  // [N,1]
    auto sy = xy.slice(1, 1, 2) * fy + cy;                  // [N,1]

    // --- Per-splat screen sigma (pixels) from world scale ---
    auto sigmaScreen = (scale.exp() * (fx / z)).clamp_min(1e-3f);  // [N,1]
    auto inv2s2 = 0.5f / (sigmaScreen * sigmaScreen + 1e-12f);     // [N,1]

    // --- Build the (2R+1)^2 patch of pixel offsets per splat ---
    auto offsets = torch::arange(-pixelRadius, pixelRadius + 1, o);  // [K]
    // d2[i, dy, dx] = dx^2 + dy^2  (same for every splat)
    auto dx2 = offsets * offsets;                                // [K]
    auto d2 = (dx2.view({1, K, 1}) + dx2.view({1, 1, K}));       // [1,K,K]

    // Per-splat pixel coordinates: [N, K, K] via broadcasting
    //   px[n, dy, dx] = sx[n] + dx,  py[n, dy, dx] = sy[n] + dy
    auto px = sx.unsqueeze(2) + offsets.view({1, 1, K});   // [N,1,K] + [1,1,K] → [N,K,K]... need care
    auto py = sy.unsqueeze(2) + offsets.view({1, 1, K});
    // Correct the broadcast: sx is [N,1], offsets along x should broadcast over the last dim,
    // and offsets along y over the middle dim. Rebuild explicitly:
    px = sx + offsets.view({1, 1, K});   // [N,1] + [1,1,K] → [N,1,K] then broadcast to [N,K,K] later
    py = sy + offsets.view({1, K, 1});   // [N,1] + [1,K,1] → [N,K,1]
    // Expand to full [N, K, K]:
    px = px.expand({N, K, K});
    py = py.expand({N, K, K});

    // --- Weight per (splat, pixel) pair ---
    auto alpha = torch::sigmoid(opacity);                   // [N,1]
    // w = alpha * exp(-d2 * inv2s2), broadcasting [N,1] * [1,K,K] * [N,1,1,1]→[N,K,K]
    auto w = alpha.view({N, 1, 1}) *
             torch::exp(-d2.view({1, K, K}) * inv2s2.view({N, 1, 1}));  // [N,K,K]

    // --- Validity mask: pixel in bounds and z > 0 ---
    auto valid = (px >= 0) & (px < float(W)) & (py >= 0) & (py < float(H));
    w = w * valid.to(o.dtype(torch::kFloat32));

    // --- Flatten for scatter_add ---
    auto wFlat   = w.reshape(-1);                                   // [N*K*K]
    auto pxFloor = px.clamp(0.f, float(W - 1)).to(torch::kLong);    // [N,K,K]
    auto pyFloor = py.clamp(0.f, float(H - 1)).to(torch::kLong);
    auto idxFlat = (pyFloor * W + pxFloor).reshape(-1);             // [N*K*K]

    // Colour per pair: broadcast color [N,3] → [N,K,K,3] → [N*K*K, 3]
    auto colorRep = color.view({N, 1, 1, 3}).expand({N, K, K, 3})
                          .reshape({N * K * K, 3});
    auto src = wFlat.unsqueeze(1) * colorRep;                       // [N*K*K, 3]

    // --- Scatter into per-pixel accumulators ---
    auto accumC = torch::zeros({H * W, 3}, o);
    auto accumW = torch::zeros({H * W, 1}, o);
    accumC.scatter_add_(0,
        idxFlat.unsqueeze(1).expand({N * K * K, 3}), src);
    accumW.scatter_add_(0,
        idxFlat.unsqueeze(1), wFlat.unsqueeze(1));

    auto out = accumC / (accumW + 1e-6f);   // [H*W, 3]
    return out.reshape({H, W, 3}).clamp(0.f, 1.f);
}

