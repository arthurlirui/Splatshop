PointCloudBA::PointCloudBA() {
    status.running = false;
    status.initialized = false;
}

PointCloudBA::~PointCloudBA() { reset(); }

void PointCloudBA::allocParams(int64_t N) {
    auto o = opts();
    tPosition = torch::zeros({N, 3}, o).set_requires_grad(config.optimizePosition);
    tColor    = torch::zeros({N, 3}, o).set_requires_grad(config.optimizeColor);
    // log-space isotropic scale -> exp() in render gives the world radius.
    tScale    = torch::full({N, 1}, std::log(config.initScale), o);
    // logit of initOpacity (frozen — not optimized in the minimal prototype).
    float p = std::clamp(config.initOpacity, 1e-3f, 1.f - 1e-3f);
    tOpacity  = torch::full({N, 1}, std::log(p / (1.f - p)), o);

    cachedN = N;
}

void PointCloudBA::freeParams() {
    tPosition.reset();
    tColor.reset();
    tScale.reset();
    tOpacity.reset();
    tTarget.reset();
    tView.reset();
    optPosition.reset();
    optColor.reset();
    cachedN = 0;
}

bool PointCloudBA::init(const PointData& pd, const BACamera& cam,
                        const uint8_t* targetRGB) {
    if (pd.count == 0 || pd.position == nullptr || pd.color == nullptr) {
        println("PointCloudBA::init: empty point cloud (count={})", pd.count);
        return false;
    }
    if (cam.width <= 0 || cam.height <= 0 || targetRGB == nullptr) {
        println("PointCloudBA::init: invalid target ({}x{})", cam.width, cam.height);
        return false;
    }

    freeParams();
    int64_t N = int64_t(pd.count);
    allocParams(N);

    // --- Source the point cloud from the device buffers (zero-copy read) ---
    {
        auto posView = torch::from_blob(
            pd.position, {N, 3},
            {3 * sizeof(float), sizeof(float)}, opts());
        tPosition.copy_(posView);
        tPosition.set_requires_grad(config.optimizePosition);
    }
    // color: uint32 RGBA8 packed (0xAABBGGRR on little-endian — see
    // SNOrbbec::loadPointCloud which writes rgba[0..2]=r,g,b then 0xff).
    {
        auto colU32 = torch::from_blob(
            pd.color, {N}, {sizeof(uint32_t)},
            TensorOptions().dtype(torch::kUInt32).device(torch::kCUDA));
        auto r = (colU32                  & 0xff).to(torch::kFloat32) / 255.f;
        auto g = (torch::bitwise_right_shift(colU32, 8)  & 0xff).to(torch::kFloat32) / 255.f;
        auto b = (torch::bitwise_right_shift(colU32, 16) & 0xff).to(torch::kFloat32) / 255.f;
        tColor = torch::stack({r, g, b}, /*dim=*/1)
                     .set_requires_grad(config.optimizeColor);
    }

    // --- Target image: HxWx3 float in [0,1] on CUDA ---
    {
        int64_t H = cam.height, W = cam.width;
        auto tHost = torch::from_blob(
            const_cast<uint8_t*>(targetRGB),
            {H, W, int64_t(3)},
            {W * 3, int64_t(3), int64_t(1)},
            TensorOptions().dtype(torch::kUInt8));
        tTarget = tHost.to(torch::kFloat32).to(torch::kCUDA) / 255.f;
    }

    // --- Camera view matrix ---
    {
        auto vHost = torch::from_blob(
            const_cast<float*>(cam.view),
            {int64_t(4), int64_t(4)},
            {int64_t(4 * sizeof(float)), int64_t(sizeof(float))},
            TensorOptions().dtype(torch::kFloat32));
        tView = vHost.to(torch::kCUDA);
    }
    cachedFx = cam.fx; cachedFy = cam.fy;
    cachedCx = cam.cx; cachedCy = cam.cy;
    cachedW  = cam.width; cachedH = cam.height;

    // --- Optimizers (one per parameter group so lr can differ) ---
    if (config.optimizePosition) {
        optPosition = std::make_unique<torch::optim::AdamW>(
            std::vector<torch::Tensor>{tPosition},
            torch::optim::AdamWOptions(config.lrPosition));
    }
    if (config.optimizeColor) {
        optColor = std::make_unique<torch::optim::AdamW>(
            std::vector<torch::Tensor>{tColor},
            torch::optim::AdamWOptions(config.lrColor));
    }

    status.pointCount = int(N);
    status.targetW = cam.width;
    status.targetH = cam.height;
    status.step = 0;
    status.loss = 0.f;
    status.initialized = true;
    status.running = true;
    println("PointCloudBA::init: N={}, target={}x{}, lrPos={}, lrCol={}",
            N, cam.width, cam.height, config.lrPosition, config.lrColor);
    return true;
}

int PointCloudBA::step(PointData& pd, CUstream stream, int steps) {
    if (!status.initialized || !status.running) return 0;
    if (steps <= 0 || cachedN == 0) return 0;

    // For the prototype, run on libtorch's default CUDA stream. SN4DGSSplats
    // does the same — it relies on the shared primary context (libtorch
    // device 0 == Splatshop's CUDA context). We synchronize the host stream
    // before the D2D copies back into the render buffers so the writes are
    // visible to the forward-only renderer's next launch on `stream`.

    // Screen-space pixel radius for the splat patch. With a fixed initScale
    // and frozen scale/opacity, sigma_screen is constant; use a 3-sigma
    // radius. Clamp to a sane upper bound to bound memory.
    auto sigmaScreenHost = (tScale.exp() * (cachedFx / 1.f)).clamp_min(1e-3f);
    float maxSigma = sigmaScreenHost.max().item<float>();
    int pixelRadius = std::max(1, std::min(16, int(std::ceil(3.f * maxSigma))));

    auto runStep = [&]() {
        if (optPosition) optPosition->zero_grad();
        if (optColor)    optColor->zero_grad();

        auto pred = renderGaussians(
            tPosition, tColor, tScale, tOpacity, tView,
            cachedFx, cachedFy, cachedCx, cachedCy, cachedW, cachedH,
            pixelRadius);

        // L1 photometric loss.
        auto l1 = torch::abs(pred - tTarget).mean();

        // SSIM loss (averaged over 3 channels).
        Tensor ssimLoss;
        {
            int win = std::min(config.ssimWindow,
                               std::min(cachedW, cachedH));
            if (win % 2 == 0) win -= 1;
            if (win < 3) win = 3;
            auto pC = pred.permute({2, 0, 1});     // [3,H,W]
            auto tC = tTarget.permute({2, 0, 1});
            auto s0 = ssimSingleChannel(pC[0], tC[0], win, 1.5f);
            auto s1 = ssimSingleChannel(pC[1], tC[1], win, 1.5f);
            auto s2 = ssimSingleChannel(pC[2], tC[2], win, 1.5f);
            ssimLoss = 1.f - (s0 + s1 + s2) / 3.f;
        }

        auto loss = config.lambdaL1 * l1 + config.lambdaSSIM * ssimLoss;
        loss.backward();

        if (optPosition) optPosition->step();
        if (optColor)    optColor->step();

        status.step    += 1;
        status.loss     = loss.item<float>();
        status.lossL1   = l1.item<float>();
        status.lossSSIM = ssimLoss.item<float>();
    };

    int done = 0;
    for (int s = 0; s < steps; ++s) {
        if (status.step >= config.maxSteps) break;
        runStep();
        done += 1;
    }

    // --- Write refined position + color back into the render buffers ---
    // The forward-only renderer reads pd.position (vec3*) and pd.color
    // (uint32 RGBA8) directly; keep them in sync with the optimized tensors.
    //
    // libtorch runs backward()/step() on its own (default) CUDA stream, while
    // `stream` here is the app's non-blocking mainstream. Without fencing,
    // the D2D copy below could race with the in-flight autograd writes on the
    // source tensors. Record an event on libtorch's current stream and make
    // `stream` wait on it so the copies read fully-updated data.
    auto torchStream = c10::cuda::getCurrentCUDAStream();
    CUevent ev;
    CURuntime::check(cuEventCreate(&ev, CU_EVENT_DISABLE_TIMING));
    CURuntime::check(cuEventRecord(ev, torchStream.stream()));
    CURuntime::check(cuStreamWaitEvent(stream, ev, 0));
    CURuntime::check(cuEventDestroy(ev));

    if (config.optimizePosition && pd.position != nullptr) {
        auto posOut = tPosition.detach().contiguous();
        CURuntime::check(cuMemcpyDtoDAsync(
            reinterpret_cast<CUdeviceptr>(pd.position),
            reinterpret_cast<CUdeviceptr>(posOut.data_ptr<float>()),
            cachedN * 3 * sizeof(float), stream));
    }
    if (config.optimizeColor && pd.color != nullptr) {
        // Repack float rgb -> uint32 RGBA8 (0xAABBGGRR little-endian).
        auto c = (tColor.detach().clamp(0.f, 1.f) * 255.f).to(torch::kUInt8);
        auto r = c.index({torch::indexing::Slice(), 0}).to(torch::kUInt32);
        auto g = c.index({torch::indexing::Slice(), 1}).to(torch::kUInt32);
        auto b = c.index({torch::indexing::Slice(), 2}).to(torch::kUInt32);
        // Use bitwise_left_shift/left_shift ops — Tensor overloads operator<<
        // / operator>> for elementwise shift, but the int-literal forms
        // resolve ambiguously on MSVC, so call the explicit ops.
        auto packed = (torch::full({r.size(0)}, 0xffu << 24, opts().dtype(torch::kUInt32))
                       | torch::bitwise_left_shift(b, 16)
                       | torch::bitwise_left_shift(g, 8)
                       | r).contiguous();
        CURuntime::check(cuMemcpyDtoDAsync(
            reinterpret_cast<CUdeviceptr>(pd.color),
            reinterpret_cast<CUdeviceptr>(packed.data_ptr<uint32_t>()),
            cachedN * sizeof(uint32_t), stream));
    }

    if (status.step >= config.maxSteps) {
        status.running = false;
        println("PointCloudBA: reached maxSteps={}, stopping.", config.maxSteps);
    }

    return done;
}

void PointCloudBA::reset() {
    freeParams();
    status.initialized = false;
    status.running = false;
    status.step = 0;
    status.loss = 0.f;
}

